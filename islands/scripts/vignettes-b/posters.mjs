// posters.mjs [card…] [--check]: writes each feature card's vignette partial, layouts/_partials/landing-vignettes/<card>.html.
// The partial = the host (.vg, its aspect ratio inline so the box is known before JS: CLS 0) holding the scene's REST frame twice,
// the desktop composition and the phone one, shown by the same max-width:640px query the engine uses. It is what a reader without
// JS, with reduced motion, or before the lazy build sees; the live build replaces it with identical pixels.
// How: load the served page (URL, default http://127.0.0.1:1381/) with every scene built (?vg-t), drive each to its `rest`
// (__vgSet), clone the host and bake each compositor sprite's COMPUTED transform and opacity inline (animations are not cloned,
// will-change dropped; a px translate is turned back into percent of the sprite's own box so the poster scales with the host),
// prefix every id with the card and composition so nothing collides. Colours stay classes + CSS vars: one poster serves both themes.
// --check: exit 1 when a partial differs from what the scenes produce now.
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '../../..'), out = join(root, 'layouts/_partials/landing-vignettes');
const URL = process.env.URL ?? 'http://127.0.0.1:1381/';
const args = process.argv.slice(2), check = args.includes('--check'), only = args.filter((a) => !a.startsWith('--'));
const b = await chromium.launch();
const errs = [];
async function shoot(vw, vh, mobile) {
	const ctx = await b.newContext({ viewport: { width: vw, height: vh }, deviceScaleFactor: 1, ...(mobile ? { isMobile: true, hasTouch: true } : {}) });
	await ctx.route(/\/islands\/.*\.js(\?.*)?$/, (r) => r.abort());
	const p = await ctx.newPage();
	p.on('pageerror', (e) => errs.push(String(e)));
	await p.goto(URL + '?vg-t=0', { waitUntil: 'load' });
	await p.waitForFunction(() => document.documentElement.dataset.vgReady === '1');
	const res = await p.evaluate(() => {
		const num = (v) => +v.toFixed(4), cards = {};
		for (const host of document.querySelectorAll('[data-vg]')) {
			const id = host.dataset.vg, spec = VG.spec(id);
			__vgSet(spec.rest);
			const clone = host.cloneNode(true), a = [...host.querySelectorAll('*')], c = [...clone.querySelectorAll('*')];
			a.forEach((n, i) => {
				const m = c[i];
				if (!(n instanceof HTMLElement) || !n.matches('.kb-root, .kb-sp')) return;
				const cs = getComputedStyle(n);
				m.style.willChange = '';
				m.style.opacity = String(num(+cs.opacity));
				const mt = cs.transform === 'none' ? [1, 0, 0, 1, 0, 0] : cs.transform.match(/matrix\(([^)]*)\)/)[1].split(',').map(Number);
				const w = parseFloat(cs.width), h = parseFloat(cs.height);
				const lin = mt.slice(0, 4).map(num).join(',');
				m.style.transform = mt[4] === 0 && mt[5] === 0 && lin === '1,0,0,1' ? '' : `translate(${+((mt[4] / w) * 100).toFixed(2)}%,${+((mt[5] / h) * 100).toFixed(2)}%) matrix(${lin},0,0)`;
				if (m.style.opacity === '1') m.style.opacity = '';
			});
			cards[id] = { html: clone.innerHTML, vb: spec.vb(window.matchMedia('(max-width: 640px)').matches) };
			cards[id].vbD = spec.vb(false); cards[id].vbM = spec.vb(true);
		}
		return cards;
	});
	await ctx.close();
	return res;
}
const D = await shoot(1440, 900, false), M = await shoot(390, 844, true);
await b.close();
if (errs.length) { console.error(errs.join('\n')); process.exit(2); }
let stale = 0;
const prefix = (html, p) => html.replace(/\bvg(\d+)\b/g, `${p}-$1`).replace(/\swill-change:[^;"]*;?/g, '').replace(/style=""/g, '');
for (const id of Object.keys(D)) {
	if (only.length && !only.includes(id)) continue;
	const [dw, dh] = D[id].vbD, [mw, mh] = M[id].vbM;
	const text = `{{- /* GENERATED by islands/scripts/vignettes-b/posters.mjs: this card's vignette host and its rest posters (desktop and phone compositions). Do not edit: change the scene and re-run. */ -}}\n`
		+ `<div class="vg" data-vg="${id}" style="--vg-ar:${dw}/${dh};--vg-ar-m:${mw}/${mh};--vg-w:${dw}"><div class="vg-p vg-p-d">${prefix(D[id].html, `p${id}d`)}</div><div class="vg-p vg-p-m">${prefix(M[id].html, `p${id}m`)}</div></div>\n`;
	const f = join(out, `${id}.html`);
	if (check) { const same = existsSync(f) && readFileSync(f, 'utf8') === text; console.log(`${same ? 'ok   ' : 'STALE'} ${id}`); if (!same) stale++; }
	else { writeFileSync(f, text); console.log(`wrote ${id}.html ${(text.length / 1024).toFixed(1)} KB`); }
}
process.exit(stale ? 1 : 0);
